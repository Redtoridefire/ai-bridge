"use strict";
const assert=require('node:assert/strict');
const {evaluate}=require('./renderer-smoke');
async function main(){
  const targets=await fetch(`http://127.0.0.1:${process.env.CDP_PORT||9225}/json`).then(r=>r.json());
  const target=targets.find(item=>item.type==='page'&&item.url.includes('index.html'));
  const result=await evaluate(target.webSocketDebuggerUrl,`(async()=>{
    document.querySelectorAll('dialog[open]').forEach(dialog=>dialog.close());
    document.querySelector('#productivity-open').click();
    document.querySelector('#tool-add').click();
    document.querySelector('#tool-title').value='Smoke skill';
    document.querySelector('#tool-content').value='Review {{code}}';
    document.querySelector('#tool-form button.primary').click();
    const skill=state.skills.find(item=>item.title==='Smoke skill');
    document.querySelector('[data-tool-favorite="'+skill.id+'"]').click();
    document.querySelector('[data-tool-use="'+skill.id+'"]').click();
    document.querySelector('[data-template-field="0"]').value='example';
    document.querySelector('#template-fill').click();
    const preview=document.querySelector('#use-preview').value;
    const view=document.querySelector('.provider-panel');
    document.querySelector('[data-tool-tab="presets"]').click();
    document.querySelector('#preset-name').value='Smoke preset';
    document.querySelector('#preset-save').click();
    document.querySelector('[data-tool-tab="layout"]').click();
    document.querySelector('#layout-ratio').value='65';
    document.querySelector('#layout-ratio').dispatchEvent(new Event('input'));
    const ratio=currentWorkspace().ratio;
    const id=currentWorkspace().panels[0].id;
    document.querySelector('[data-panel-focus="'+id+'"]').click();
    const focused=[...document.querySelectorAll('.provider-panel')].filter(el=>!el.hidden).length;
    openTools('layout');document.querySelector('#layout-reset').click();
    const preserved=view===document.querySelector('.provider-panel');
    const restored=[...document.querySelectorAll('.provider-panel')].filter(el=>!el.hidden).length;
    const originalWorkspace=state.activeWorkspaceId;
    document.querySelector('[data-tool-tab="presets"]').click();
    const preset=state.presets.find(item=>item.title==='Smoke preset');
    document.querySelector('[data-preset-use="'+preset.id+'"]').click();
    const freshWorkspace=state.activeWorkspaceId;
    const isolated=Core.activeWorkspace(state).panels.every(panel=>!viewCache.get(panel.id)?.getAttribute('partition')?.includes('panel-claude'));
    const switcher=document.querySelector('#workspace-select');switcher.value=originalWorkspace;switcher.dispatchEvent(new Event('change'));
    const mounted=view.isConnected&&!view.hidden;
    state.workspaces=state.workspaces.filter(workspace=>workspace.id!==freshWorkspace);renderPanels();
    const backup=await bridge.saveBackup(JSON.stringify(Core.exportPayload(state)));
    const list=await bridge.listBackups();
    const read=backup.ok?await bridge.readBackup(backup.name):null;
    const roundtrip=read?.ok?Core.importPayload(read.content).skills.some(item=>item.id===skill.id):false;
    state.skills=state.skills.filter(item=>item.id!==skill.id);state.presets=state.presets.filter(item=>item.title!=='Smoke preset');persist();
    toolsDialog.close();
    return {preview,favorite:skill.favorite,ratio,focused,preserved,restored,isolated,mounted,backup:backup.ok,backupError:backup.error,list:list.ok,roundtrip,storageWritable};
  })()`);
  assert.equal(result.preview,'Review example');assert.equal(result.favorite,true);assert.equal(result.ratio,65);assert.equal(result.focused,1);assert.equal(result.preserved,true);assert.equal(result.restored,2);assert.equal(result.list,true);
  if(result.storageWritable){assert.equal(result.backup,true);assert.equal(result.roundtrip,true);}else{assert.equal(result.backup,false);assert.match(result.backupError,/encryption.*unavailable/i);}
  assert.equal(result.isolated,true);assert.equal(result.mounted,true);
  console.log('Productivity workflows passed',JSON.stringify(result));
}
main().catch(error=>{console.error(error);process.exitCode=1;});
